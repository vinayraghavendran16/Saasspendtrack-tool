import assert from 'node:assert/strict';
import {reviewFinancialEvidence} from '../functions/_shared/financial-evidence-review.js';
import {onRequestPost} from '../functions/api/decisions/financial-review.js';
const evaluation={scopeKey:'contract-a',periodKey:'2027',currency:'USD',baselineMinor:'120000',alternatives:[{id:'resize',eligible:true,netSavingsMinor:'24000'}]};
const invoice={id:'i1',contract_id:'contract-a',source_id:'erp',source_record_id:'1',kind:'invoice',effective_date:'2027-06-01',currency:'USD',amount_minor:104000};
const credit={...invoice,id:'c1',source_record_id:'2',kind:'credit',amount_minor:2000};
const input={evaluation,approval:{status:'approved',revision:1,alternativeId:'resize'},contractId:'contract-a',rows:[invoice,credit],asOf:'2028-01-01'};
const result=reviewFinancialEvidence(input);
assert.equal(result.actualMinor,'102000');
assert.equal(result.varianceMinor,'18000');
assert.equal(result.varianceToExpectedMinor,'-6000');
assert.equal(result.learningEligible,false);
assert.equal(result.completeness,'not_established');
assert.throws(()=>reviewFinancialEvidence({...input,asOf:'2027-12-31'}));
assert.throws(()=>reviewFinancialEvidence({...input,rows:[invoice,{...credit,source_record_id:'1'}]}));
assert.throws(()=>reviewFinancialEvidence({...input,rows:[{...invoice,contract_id:'other'}]}));
assert.throws(()=>reviewFinancialEvidence({...input,rows:[{...invoice,currency:'EUR'}]}));
assert.throws(()=>reviewFinancialEvidence({...input,rows:[{...invoice,effective_date:'2028-01-01'}]}));
assert.throws(()=>reviewFinancialEvidence({...input,rows:[]}));
assert.throws(()=>reviewFinancialEvidence({...input,approval:{...input.approval,status:'pending'}}));
const request=new Request('https://app.saasspendtrack.com/api/decisions/financial-review',{method:'POST'});
assert.equal((await onRequestPost({request,env:{}})).status,404);
assert.equal((await onRequestPost({request,env:{DECISION_INTELLIGENCE_ENABLED:'true'}})).status,401);
console.log('14 financial evidence assertions passed');
