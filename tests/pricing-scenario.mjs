import assert from 'node:assert/strict';
import {priceTiered} from '../functions/_shared/commercial-pricing.js';
import {comparePricing} from '../functions/_shared/pricing-scenario.js';
import {experiencePreset} from '../functions/_shared/experience-presets.js';
const tiers=[{upTo:100,unitMinor:1000},{upTo:null,unitMinor:800}];
assert.equal(priceTiered({model:'graduated',quantity:150,tiers}).amountMinor,'140000');
assert.equal(priceTiered({model:'volume',quantity:150,tiers}).amountMinor,'120000');
assert.equal(priceTiered({model:'volume',quantity:0,tiers,minimumMinor:500}).amountMinor,'500');
assert.equal(priceTiered({model:'graduated',quantity:100,tiers}).amountMinor,'100000');
assert.throws(()=>priceTiered({model:'volume',quantity:101,tiers:[tiers[0]]}));
const offers=[{id:'seat',currency:'USD',components:[{model:'seat',unitMinor:1000}]},{id:'hybrid',currency:'USD',components:[{model:'fixed',unitMinor:20000},{model:'seat',unitMinor:500}]}];
const result=comparePricing({currency:'USD',quantities:[10,100],offers});
assert.equal(result[0].options[0].id,'seat');
assert.equal(result[1].options[0].id,'hybrid');
assert.equal(result[1].options[0].annualMinor,'840000');
assert.throws(()=>comparePricing({currency:'EUR',quantities:[10],offers}));
assert.deepEqual(experiencePreset('cfo',['licence-usage','approvals']),['approvals']);
assert.deepEqual(experiencePreset('cro',[]),[]);
console.log('pricing scenario and persona fixtures passed');
